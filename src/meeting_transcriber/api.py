"""Simple Python API for getting a transcript.

Two functions cover the common cases:

* :func:`transcribe_audio` — audio only, no video analysis;
* :func:`transcribe_video` — audio + OCR of slides/code shown in the video.

Both write outputs next to the input file unless ``output_dir`` is given.
The LLM meeting report is not generated by these helpers; use the CLI
``report`` command for that.
"""

from __future__ import annotations

from pathlib import Path

from .config import AppConfig, load_config
from .pipeline.runner import Pipeline, RunResult


def _base_config(config: str | Path | None) -> AppConfig:
    if config is not None:
        return load_config(config)
    default = Path("config/default.yaml")
    return load_config(default if default.is_file() else None)


def _output_dir(input_path: Path, output_dir: str | Path | None) -> Path:
    if output_dir is not None:
        return Path(output_dir).expanduser().resolve()
    return input_path.expanduser().resolve().parent


def transcribe_audio(
    input_path: str | Path,
    output_dir: str | Path | None = None,
    *,
    config: str | Path | None = None,
    language: str | None = None,
    device: str | None = None,
    num_speakers: int | None = None,
    max_speakers: int | None = None,
    force: bool = False,
) -> RunResult:
    """Transcribe an audio or video file without using its video frames."""

    source = Path(input_path).expanduser().resolve()
    cfg = _base_config(config)
    cfg.visual.enabled = False
    cfg.llm.enabled = False
    if language:
        cfg.language = language
    cfg.paths.output_dir = str(_output_dir(source, output_dir))
    return Pipeline(
        cfg,
        force=force,
        skip_llm=True,
        num_speakers=num_speakers,
        max_speakers=max_speakers,
        device=device,
    ).run(source)


def transcribe_video(
    input_path: str | Path,
    output_dir: str | Path | None = None,
    *,
    config: str | Path | None = None,
    language: str | None = None,
    device: str | None = None,
    num_speakers: int | None = None,
    max_speakers: int | None = None,
    keep_frames: bool = True,
    force: bool = False,
) -> RunResult:
    """Transcribe a video and use OCR of slides/code as report context."""

    source = Path(input_path).expanduser().resolve()
    cfg = _base_config(config)
    cfg.visual.enabled = True
    cfg.visual.keep_code_frames = keep_frames
    cfg.llm.enabled = False
    if language:
        cfg.language = language
    cfg.paths.output_dir = str(_output_dir(source, output_dir))
    return Pipeline(
        cfg,
        force=force,
        skip_llm=True,
        num_speakers=num_speakers,
        max_speakers=max_speakers,
        device=device,
    ).run(source)


__all__ = ["transcribe_audio", "transcribe_video"]
